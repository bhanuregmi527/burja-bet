import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

const ICONS = [
  { symbol: 'heart', lucide: 'Heart' },
  { symbol: 'spade', lucide: 'Spade' },
  { symbol: 'diamond', lucide: 'Diamond' },
  { symbol: 'club', lucide: 'Club' },
  { symbol: 'crown', lucide: 'Crown' },
  { symbol: 'flag', lucide: 'Flag' },
];

function extractIconNodeLiteral(bundleSource, iconName) {
  const marker = `const ${iconName} = createLucideIcon(\"${iconName}\",`;
  const markerIndex = bundleSource.indexOf(marker);
  if (markerIndex < 0) {
    throw new Error(`Icon not found in bundle: ${iconName}`);
  }

  let cursor = markerIndex + marker.length;
  while (cursor < bundleSource.length && /\s/.test(bundleSource[cursor])) cursor++;

  if (bundleSource[cursor] !== '[') {
    throw new Error(`Expected iconNode array for ${iconName}`);
  }

  let depth = 0;
  const start = cursor;

  for (; cursor < bundleSource.length; cursor++) {
    const ch = bundleSource[cursor];

    if (ch === '"' || ch === "'") {
      const quote = ch;
      cursor++;
      while (cursor < bundleSource.length) {
        const c = bundleSource[cursor];
        if (c === '\\') {
          cursor += 2;
          continue;
        }
        if (c === quote) break;
        cursor++;
      }
      continue;
    }

    if (ch === '[') depth++;
    else if (ch === ']') {
      depth--;
      if (depth === 0) {
        cursor++;
        break;
      }
    }
  }

  return bundleSource.slice(start, cursor);
}

function extractIconNode(bundleSource, iconName) {
  const literal = extractIconNodeLiteral(bundleSource, iconName);
  const iconNode = vm.runInNewContext(`(${literal})`, {}, { timeout: 1000 });

  if (!Array.isArray(iconNode)) {
    throw new Error(`Invalid iconNode parsed for ${iconName}`);
  }

  return iconNode;
}

function toConstName(symbol) {
  return `${symbol.toUpperCase()}_ICON_NODE`;
}

function generateTs(iconNodesBySymbol) {
  const header = `/* eslint-disable */\n/*\n  AUTO-GENERATED FILE\n  Generated by: scripts/generate-lucide-icon-nodes.mjs\n  Do not edit by hand.\n*/\n\n`;

  const typeBlock =
    `export type LucideIconNode = Array<[string, Record<string, string>]>;\n\n`;

  const keys = Object.keys(iconNodesBySymbol).sort();

  const constants = keys
    .map((symbol) => {
      const constName = toConstName(symbol);
      const value = JSON.stringify(iconNodesBySymbol[symbol], null, 2);
      return `export const ${constName}: LucideIconNode = ${value};\n`;
    })
    .join('\n');

  const mapEntries = keys
    .map((symbol) => `  ${JSON.stringify(symbol)}: ${toConstName(symbol)},`)
    .join('\n');

  const mapBlock =
    `export const LUCIDE_ICON_NODES_BY_SYMBOL: Record<string, LucideIconNode> = {\n${mapEntries}\n};\n`;

  return header + typeBlock + constants + '\n' + mapBlock;
}

function main() {
  const bundlePath = require.resolve('lucide-react/dist/cjs/lucide-react.js');
  const bundleSource = fs.readFileSync(bundlePath, 'utf8');

  const iconNodesBySymbol = {};

  for (const { symbol, lucide } of ICONS) {
    const node = extractIconNode(bundleSource, lucide);
    iconNodesBySymbol[symbol] = node;
  }

  const output = generateTs(iconNodesBySymbol);
  const outPath = path.resolve(process.cwd(), 'lib', 'lucideIconNodes.ts');
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, output, 'utf8');

  // eslint-disable-next-line no-console
  console.log(`Generated ${outPath}`);
}

main();
